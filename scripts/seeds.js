function validateProduct(product) {
  if (product.minimumPrice > product.currentPrice) {
    throw new Error(`${product.id}: 현재 가격이 최저 판매 가격보다 낮습니다.`);
  }

  if (product.currentPrice > product.initialPrice) {
    throw new Error(`${product.id}: 현재 가격이 최초 등록 가격보다 높습니다.`);
  }

  if (product.priceHistory.length === 0) {
    throw new Error(`${product.id}: 가격 변경 이력이 필요합니다.`);
  }
}

products.forEach(validateProduct);
